import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { services } from '../src/catalog.mjs';

const projectRoot = fileURLToPath(new URL('..', import.meta.url));
const articlesPath = new URL('../src/articles.ts', import.meta.url);
const appPath = new URL('../src/App.tsx', import.meta.url);
const sitemapPath = new URL('../public/sitemap.xml', import.meta.url);
const robotsPath = new URL('../public/robots.txt', import.meta.url);
const llmsPath = new URL('../public/llms.txt', import.meta.url);

const excludedRoutes = new Set(['/process', '/workspace', '/demo-workspace', '/internal', '/sign-in', '/invite', '/privacy', '/terms']);

function canonicalOrigin(value = '') {
  const candidate = value.trim();
  if (!candidate) return '';
  const url = new URL(candidate);
  const local = ['localhost', '127.0.0.1', '::1'].includes(url.hostname);
  if (url.protocol !== 'https:' && !(local && url.protocol === 'http:')) {
    throw new Error('CANONICAL_ORIGIN must use HTTPS, except for an explicit localhost origin.');
  }
  if (url.pathname !== '/' || url.search || url.hash) {
    throw new Error('CANONICAL_ORIGIN must contain only the scheme and host, without a path, query, or fragment.');
  }
  return url.origin;
}

function articleRecords(source) {
  const records = [...source.matchAll(/"slug": "([^"]+)"[\s\S]*?"title": ("(?:\\.|[^"\\])*")[\s\S]*?"description": ("(?:\\.|[^"\\])*")[\s\S]*?"updated": "(\d{4}-\d{2}-\d{2})"/g)]
    .map(([, slug, title, description, lastmod]) => ({ slug, title: JSON.parse(title), description: JSON.parse(description), lastmod }));
  if (!records.length) throw new Error('No article routes were found in src/articles.ts.');
  return records;
}

function articleRoutes(source) {
  return articleRecords(source).map(({ slug, lastmod }) => ({ path: `/blog/${slug}`, lastmod }));
}

function staticRoutes(source) {
  const routes = [...source.matchAll(/<Route\s+path="([^"]+)"/g)]
    .map(([, path]) => path)
    .filter(path => !path.includes(':') && path !== '*' && !excludedRoutes.has(path));
  if (!routes.length) throw new Error('No public static routes were found in src/App.tsx.');
  return routes;
}

function escapeXml(value) {
  return value.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;').replaceAll("'", '&apos;');
}

function buildSitemap({ appSource, articleSource, origin = '' }) {
  const records = [
    ...staticRoutes(appSource).map(path => ({ path })),
    ...services.map(service => ({ path: `/services/${service.slug}` })),
    ...articleRoutes(articleSource),
  ];
  const paths = records.map(record => record.path);
  const duplicates = paths.filter((path, index) => paths.indexOf(path) !== index);
  if (duplicates.length) throw new Error(`Duplicate sitemap routes: ${[...new Set(duplicates)].join(', ')}`);
  if (paths.some(path => !path.startsWith('/') || path.includes('?') || path.includes('#'))) {
    throw new Error('Sitemap routes must be clean, root-relative paths.');
  }
  const rows = records.map(record => {
    const loc = escapeXml(`${origin}${record.path}`);
    const lastmod = record.lastmod ? `<lastmod>${record.lastmod}</lastmod>` : '';
    return `  <url><loc>${loc}</loc>${lastmod}</url>`;
  });
  return `<?xml version="1.0" encoding="UTF-8"?>\n<!-- Generated by scripts/generate-sitemap.mjs. Do not edit manually. -->\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${rows.join('\n')}\n</urlset>\n`;
}

function buildRobots(origin = '') {
  return `User-agent: *\nAllow: /\nDisallow: /workspace\nDisallow: /demo-workspace\nDisallow: /internal\nDisallow: /sign-in\nDisallow: /invite\nDisallow: /privacy\nDisallow: /terms\n\nSitemap: ${origin}/sitemap.xml\n`;
}

function buildLlms({ articleSource, origin = '' }) {
  const href = path => `${origin}${path}`;
  const serviceLinks = services.map(service => `- [${service.name}](${href(`/services/${service.slug}`)}): ${service.trigger}`);
  const articleLinks = articleRecords(articleSource).map(article => `- [${article.title}](${href(`/blog/${article.slug}`)}): ${article.description}`);
  return `# Sthuthi Securities\n\n> Authorized cybersecurity testing, remediation, and retesting for web applications, APIs, cloud systems, SaaS products, and AI agents.\n\nSthuthi Securities is a product from Sthuthi Technologies, LLC. Public material describes scoped services, pricing, assessment methods, security practices, field guides, worksheets, and evidence-led security articles. Demo workspaces, authentication routes, draft legal pages, and internal delivery screens are not public reference material.\n\n## Primary pages\n\n- [Home](${href('/')}): Security testing for applications, cloud systems, and AI agents.\n- [Services](${href('/services')}): Service boundaries, pricing, timing, access needs, and deliverables.\n- [Pricing](${href('/pricing')}): Starting prices and commercial scope.\n- [How assessments work](${href('/how-it-works')}): Authorization, scoping, testing, reporting, remediation, and retesting.\n- [Security and data handling](${href('/security')}): Evidence, access, retention, secrets, and provider boundaries.\n- [Resources](${href('/resources')}): Seven long-form security guides and their downloadable worksheet packs.\n- [Security field notes](${href('/blog')}): Research and practical guidance for security buyers and engineering teams.\n- [Discuss a project](${href('/request')}): Assessment scoping request.\n\n## Security services\n\n${serviceLinks.join('\n')}\n\n## Security field notes\n\n${articleLinks.join('\n')}\n\n## Optional\n\n- [Sample assessment report](${href('/sample-report')}): An illustrative finding with evidence, impact, remediation, and retest state.\n- [About Sthuthi Securities](${href('/about')}): Company and operating approach.\n`;
}

async function generateSitemap({ write = true } = {}) {
  const origin = canonicalOrigin(process.env.CANONICAL_ORIGIN);
  const [appSource, articleSource] = await Promise.all([readFile(appPath, 'utf8'), readFile(articlesPath, 'utf8')]);
  const sitemap = buildSitemap({ appSource, articleSource, origin });
  const robots = buildRobots(origin);
  const llms = buildLlms({ articleSource, origin });
  if (write) {
    await writeFile(sitemapPath, sitemap);
    await writeFile(robotsPath, robots);
    await writeFile(llmsPath, llms);
    console.log(`Generated sitemap with ${(sitemap.match(/<url>/g) || []).length} indexable URLs${origin ? ` for ${origin}` : ' using root-relative local URLs'}.`);
  }
  return { sitemap, robots, llms, origin };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) await generateSitemap();

export { articleRecords, articleRoutes, buildLlms, buildRobots, buildSitemap, canonicalOrigin, excludedRoutes, generateSitemap, projectRoot, staticRoutes };
